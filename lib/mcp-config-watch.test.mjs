import assert from "node:assert/strict";
import { mkdir, mkdtemp, rm, writeFile, rename } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { createJiti } from "jiti";
const { watchMcpConfigFiles } = await createJiti(import.meta.url).import("./mcp-config-watch.ts");
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
test("file observers detect create and atomic replace, share listeners and stop after dispose", { timeout: 15000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), "pi-mcp-watch-")); const agent = join(root, "agent"); await mkdir(agent);
  let one = 0, two = 0;
  const stopOne = watchMcpConfigFiles(agent, root, () => one++), stopTwo = watchMcpConfigFiles(agent, root, () => two++);
  t.after(async () => { stopOne(); stopTwo(); await rm(root, { recursive: true, force: true }); });
  await delay(1300); const initial = one;
  await writeFile(join(agent, "mcp.json"), "{}");
  for (let i = 0; one === initial && i < 40; i++) await delay(100);
  assert.ok(one > initial); assert.equal(one, two);
  stopOne(); const frozen = one, before = two;
  await writeFile(join(agent, "new.json"), '{"mcpServers":{}}'); await rename(join(agent, "new.json"), join(agent, "mcp.json"));
  for (let i = 0; two === before && i < 40; i++) await delay(100);
  assert.ok(two > before); assert.equal(one, frozen);
  stopTwo(); const final = two; await writeFile(join(agent, "mcp.json"), '{"mcpServers":{"off":{"enabled":false}}}'); await delay(1400);
  assert.equal(two, final);
});
